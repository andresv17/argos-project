#!/usr/bin/env node
/**
 * Compilador del contrato operativo de la Feature 003 (ops.openapi.yaml) [INV-ARCH-003].
 * Valida el documento (OpenAPI 3.1 con openapi-typescript, 3 operaciones esperadas, sin rutas de dominio de la 002,
 * sobre RFC 9457 en los errores) y emite openapi-types.ts. Nunca escribe fuera de --out.
 *
 * Uso: node scripts/codegen-ops.mjs --contracts DIR --out DIR
 *
 * @implements INV-ARCH-003
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse as parseYaml } from 'yaml';

const fail = (message) => {
  console.error(`[SDD Ops Compiler] ${message}`);
  process.exit(1);
};
const argValue = (flag) => {
  const i = process.argv.indexOf(flag);
  return i >= 0 && process.argv[i + 1] ? resolve(process.argv[i + 1]) : fail(`falta ${flag}`);
};

const contractsDir = argValue('--contracts');
const outDir = argValue('--out');
const file = join(contractsDir, 'openapi/ops.openapi.yaml');
if (!existsSync(file)) fail(`contrato ausente: ${file}`);

const doc = parseYaml(readFileSync(file, 'utf8'));
if (!/^3\.1\./.test(String(doc.openapi))) fail(`se exige OpenAPI 3.1.x (encontrado ${doc.openapi})`);
const meta = doc.info?.['x-sdd-metadata'];
if (!meta?.version || !meta?.status) fail('info.x-sdd-metadata sin version/status');

const EXPECTED = { getHealthz: 'get /healthz', getReadyz: 'get /readyz', runMaintenance: 'post /internal/maintenance' };
const found = {};
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  if (path.startsWith('/api')) fail(`ruta de dominio no permitida en ops: ${path}`);
  for (const [method, op] of Object.entries(item)) {
    if (!op?.operationId) continue;
    found[op.operationId] = `${method} ${path}`;
    for (const [status, response] of Object.entries(op.responses ?? {})) {
      if (/^[45]/.test(status) && !response.content?.['application/problem+json']) {
        fail(`${op.operationId} ${status}: los errores deben ser application/problem+json (RFC 9457)`);
      }
    }
  }
}
if (JSON.stringify(Object.entries(found).sort()) !== JSON.stringify(Object.entries(EXPECTED).sort())) {
  fail(`operaciones inesperadas: ${JSON.stringify(found)}`);
}

const ast = await openapiTS(pathToFileURL(file));
const types = astToString(ast).replace('export type $defs = Record<string, never>;\n', '');
mkdirSync(outDir, { recursive: true });
const banner = [
  '/**',
  ' * AUTO-GENERATED by scripts/codegen-ops.mjs — DO NOT EDIT MANUALLY [INV-ARCH-003]',
  ` * Source: contracts/openapi/ops.openapi.yaml (v${meta.version}, ${meta.status})`,
  ` * @implements ${[...new Set(['INV-ARCH-003', ...(meta.traceability ?? [])])].sort().join(', ')}`,
  ' */',
].join('\n');
writeFileSync(join(outDir, 'openapi-types.ts'), `${banner}\n\n${types.trimEnd()}\n`, 'utf8');
console.log(`[SDD Ops Compiler] ${Object.keys(found).length} operaciones validadas; emitido ${join(outDir, 'openapi-types.ts')}`);
