#!/usr/bin/env node
/**
 * Compilador de catálogos de la Feature 004 (contracts/catalogs/*.catalog.json -> src/generated/catalogs/) [INV-ARCH-003].
 * Valida el catálogo de razas (patrón de código, prefijo igual a la especie, unicidad, Criolla primero y Otra última por especie)
 * y emite breeds.catalog.ts determinista (entradas por especie y orden). Nunca escribe fuera de --out.
 *
 * Uso: node scripts/codegen-catalogs.mjs --contracts DIR --out DIR
 *
 * @implements INV-ARCH-003, REQ-RAZ-001, INV-RAZ-001
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const fail = (message) => {
  console.error(`[SDD Catalog Compiler] ${message}`);
  process.exit(1);
};
const argValue = (flag) => {
  const i = process.argv.indexOf(flag);
  return i >= 0 && process.argv[i + 1] ? resolve(process.argv[i + 1]) : fail(`falta ${flag}`);
};

const contractsDir = argValue('--contracts');
const outDir = argValue('--out');
const catalogsDir = join(contractsDir, 'catalogs');
if (!existsSync(catalogsDir)) fail(`carpeta de catálogos ausente: ${catalogsDir}`);

const PREFIX = { CANINE: 'DOG_', FELINE: 'CAT_' };
const ENTRY_KEYS = ['code', 'species', 'deprecated', 'label', 'order'];
const fold = (text) => text.normalize('NFD').replace(/\p{M}/gu, '');

function loadBreeds() {
  const file = join(catalogsDir, 'breeds.catalog.json');
  if (!existsSync(file)) fail(`catálogo ausente: ${file}`);
  let doc;
  try {
    doc = JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    return fail(`JSON inválido en breeds.catalog.json: ${error.message}`);
  }
  if (doc.catalogId !== 'BREEDS') fail('catalogId debe ser BREEDS');
  if (!/^\d+\.\d+\.\d+$/.test(doc.catalogVersion ?? '')) fail('catalogVersion debe ser semver');
  let pattern;
  try {
    pattern = new RegExp(doc.codePattern);
  } catch {
    return fail('codePattern inválido');
  }
  if (!Array.isArray(doc.entries) || doc.entries.length === 0) fail('entries vacío');
  const seen = new Set();
  for (const entry of doc.entries) {
    const keys = Object.keys(entry).sort();
    if (keys.join() !== [...ENTRY_KEYS].sort().join()) fail(`claves no cerradas en ${entry.code ?? '?'}: ${keys.join(', ')}`);
    if (!pattern.test(entry.code)) fail(`code fuera del patrón ${doc.codePattern}: ${entry.code}`);
    if (!(entry.species in PREFIX)) fail(`especie sin catálogo en ${entry.code}: ${entry.species}`);
    if (!entry.code.startsWith(PREFIX[entry.species])) fail(`prefijo del code distinto de la especie en ${entry.code} (${entry.species}) [SC-CAT-032]`);
    if (seen.has(entry.code)) fail(`code duplicado: ${entry.code}`);
    seen.add(entry.code);
    if (typeof entry.label !== 'string' || entry.label.trim() === '' || typeof entry.deprecated !== 'boolean') fail(`label o deprecated inválido en ${entry.code}`);
  }
  // order se recalcula al compilar (TECHDEBT-004-05): Criolla 1; el resto alfabético sin tildes de 10 en 10; Otra 9999.
  const entries = [];
  for (const species of Object.keys(PREFIX)) {
    const own = doc.entries.filter((e) => e.species === species);
    const criolla = own.filter((e) => e.code.endsWith('_CRIOLLA'));
    const otra = own.filter((e) => e.code.endsWith('_OTHER'));
    if (criolla.length !== 1 || otra.length !== 1) fail(`${species} debe tener exactamente una Criolla y una Otra`);
    const rest = own.filter((e) => !criolla.includes(e) && !otra.includes(e)).sort((a, b) => fold(a.label).localeCompare(fold(b.label), 'es') || a.code.localeCompare(b.code));
    entries.push({ ...criolla[0], order: 1 }, ...rest.map((e, i) => ({ ...e, order: (i + 1) * 10 })), { ...otra[0], order: 9999 });
  }
  return { doc, entries: entries.map((e) => ({ code: e.code, species: e.species, label: e.label, order: e.order, deprecated: e.deprecated })) };
}

const { doc, entries } = loadBreeds();
const source = `contracts/catalogs/breeds.catalog.json (v${doc.catalogVersion}, ${doc.status})`;
const body = [
  '/**',
  ' * AUTO-GENERATED by scripts/codegen-catalogs.mjs — DO NOT EDIT MANUALLY [INV-ARCH-003]',
  ` * Source: ${source}`,
  ' * @implements INV-ARCH-003, REQ-RAZ-001, INV-RAZ-001',
  ' */',
  `export const BREEDS_CATALOG_VERSION = ${JSON.stringify(doc.catalogVersion)};`,
  `export const BREEDS_CATALOG_STATUS = ${JSON.stringify(doc.status)};`,
  `export const BREED_CODE_PATTERN = ${JSON.stringify(doc.codePattern)};`,
  '',
  `export const BREEDS = ${JSON.stringify(entries, null, 2)} as const;`,
  '',
  'export type BreedEntry = (typeof BREEDS)[number];',
  'export type BreedCode = BreedEntry[\'code\'];',
  "export type BreedSpecies = BreedEntry['species'];",
  '',
  'export const BREED_CODES: readonly BreedCode[] = BREEDS.map((entry) => entry.code);',
  '',
  'export function findBreed(code: string): BreedEntry | undefined {',
  '  return BREEDS.find((entry) => entry.code === code);',
  '}',
  '',
  '/** Razas vigentes (no deprecadas) de una especie, en el orden del catálogo. */',
  "export function breedsFor(species: BreedSpecies): readonly BreedEntry[] {",
  '  return BREEDS.filter((entry) => entry.species === species && !entry.deprecated);',
  '}',
  '',
].join('\n');

mkdirSync(outDir, { recursive: true });
for (const entry of readdirSync(outDir)) rmSync(join(outDir, entry), { recursive: true, force: true });
writeFileSync(join(outDir, 'breeds.catalog.ts'), body, 'utf8');
writeFileSync(join(outDir, 'index.ts'), `/**\n * AUTO-GENERATED by scripts/codegen-catalogs.mjs — DO NOT EDIT MANUALLY [INV-ARCH-003]\n * @implements INV-ARCH-003\n */\nexport * from './breeds.catalog.ts';\n`, 'utf8');
console.log(`[SDD Catalog Compiler] breeds.catalog.ts: ${entries.length} razas (catalogVersion ${doc.catalogVersion}) -> ${outDir}`);
