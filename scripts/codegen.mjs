export function isValidIsoCalendarDate(dateStr: string): boolean {
  if (!ISO_DATE_REGEX.test(dateStr)) {
    return false;
  }
  const parts = dateStr.split('-');
  const year = Number(parts[0]);
  const month = Number(parts[1]);
  const day = Number(parts[2]);
  if (month < 1 || month > 12 || day < 1 || day > 31) {
    return false;
  }
  const daysInMonths = [31, isLeapYear(year) ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  const maxDay = daysInMonths[month - 1];
  return maxDay !== undefined && day <= maxDay;
}

function isLeapYear(year: number): boolean {
  return (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
}

export function isValidUuid(value: string): boolean {
  return UUID_REGEX.test(value);
}

export function isValidIsoDateTime(value: string): boolean {
  if (!ISO_DATETIME_REGEX.test(value)) {
    return false;
  }
  const datePart = value.slice(0, 10);
  return isValidIsoCalendarDate(datePart);
}

