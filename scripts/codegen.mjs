#!/usr/bin/env node
/**
 * Generador determinista de src/generated/ desde contracts/ [INV-ARCH-003, TASK-102].
 *
 * Entradas (solo lectura): contracts/schemas/*.schema.json, contracts/errors/error-catalog.json,
 * contracts/state-machines/*.machine.json, contracts/openapi/*.openapi.yaml.
 * Salidas: src/generated/** (no editar a mano).
 *
 * Uso: node scripts/codegen.mjs [--contracts DIR] [--out DIR]
 *
 * @implements INV-ARCH-003
 */
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneModule from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import { compile as compileTypes } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse as parseYaml } from 'yaml';

const standaloneCode = standaloneModule.default ?? standaloneModule;

// ---------------------------------------------------------------------------
// Argumentos
// ---------------------------------------------------------------------------
const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '..');

function argValue(flag, fallback) {
  const i = process.argv.indexOf(flag);
  return i >= 0 && process.argv[i + 1] ? resolve(process.argv[i + 1]) : fallback;
}

const contractsDir = argValue('--contracts', join(repoRoot, 'contracts'));
const outDir = argValue('--out', join(repoRoot, 'src/generated'));

/** IDs retirados que no deben aparecer en ninguna salida generada (v2.2.0). */
const RETIRED_IDS = ['STATE-PET-QUOTA-001', 'ERR-PET-QUOTA-EXCEEDED'];

function fail(message) {
  console.error(`[codegen] ERROR: ${message}`);
  process.exit(1);
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    return fail(`no se pudo leer ${path}: ${error.message}`);
  }
}

// ---------------------------------------------------------------------------
// Utilidades de salida
// ---------------------------------------------------------------------------
const emitted = new Map();

function emit(relPath, content) {
  emitted.set(relPath, content.endsWith('\n') ? content : `${content}\n`);
}

function banner({ sources, implementsIds }) {
  const lines = [
    '/**',
    ' * AUTO-GENERATED by scripts/codegen.mjs — DO NOT EDIT MANUALLY [INV-ARCH-003]',
    ...sources.map((s) => ` * Source: ${s}`),
    ` * @implements ${[...new Set(['INV-ARCH-003', ...implementsIds])].sort().join(', ')}`,
    ' */',
  ];
  return lines.join('\n');
}

function metaOf(doc) {
  const meta = doc['x-sdd-metadata'];
  if (!meta) fail('contrato sin x-sdd-metadata');
  return meta;
}

function sourceLabel(relPath, doc) {
  const meta = metaOf(doc);
  return `${relPath} (v${meta.version}, ${meta.status})`;
}

function pascal(id) {
  return id
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
}

function screamingSnake(id) {
  return id.replace(/[^A-Za-z0-9]+/g, '_').toUpperCase();
}

// ---------------------------------------------------------------------------
// 1. Carga de contratos
// ---------------------------------------------------------------------------
const schemasDir = join(contractsDir, 'schemas');
const schemaFiles = readdirSync(schemasDir)
  .filter((f) => f.endsWith('.schema.json'))
  .sort();
if (schemaFiles.length === 0) fail(`sin esquemas en ${schemasDir}`);

const schemas = schemaFiles.map((file) => {
  const doc = readJson(join(schemasDir, file));
  if (!doc.$id) fail(`${file} no declara $id`);
  return { file, rel: `contracts/schemas/${file}`, doc };
});

const catalog = readJson(join(contractsDir, 'errors/error-catalog.json'));
const errorEntries = catalog.errors;
if (!errorEntries || typeof errorEntries !== 'object') fail('error-catalog.json sin "errors"');

const machinesDir = join(contractsDir, 'state-machines');
const machineFiles = readdirSync(machinesDir)
  .filter((f) => f.endsWith('.machine.json'))
  .sort();
const machineDocs = machineFiles.map((file) => ({
  file,
  rel: `contracts/state-machines/${file}`,
  doc: readJson(join(machinesDir, file)),
}));

const openapiDir = join(contractsDir, 'openapi');
const openapiFile = readdirSync(openapiDir).find((f) => f.endsWith('.openapi.yaml'));
if (!openapiFile) fail(`sin OpenAPI en ${openapiDir}`);
const openapiPath = join(openapiDir, openapiFile);
const openapiDoc = parseYaml(readFileSync(openapiPath, 'utf8'));

// ---------------------------------------------------------------------------
// 2. Ajv standalone (todos los esquemas registrados por $id antes de compilar)
// ---------------------------------------------------------------------------
// strictTypes: true (explícito). Los contratos de TASK-102 declaran "type" local junto a maxLength;
// no se desactiva la validación estricta de tipos. Ver CC-102-D1 (revertido).
const ajv = new Ajv2020({
  strict: true,
  strictTypes: true,
  allowUnionTypes: true,
  allErrors: true,
  multipleOfPrecision: 2,
  code: { source: true, optimize: true },
});
addFormats(ajv);
ajv.addKeyword({ keyword: 'x-sdd-metadata', schemaType: 'object' });
ajv.addKeyword({ keyword: 'x-sdd-status', schemaType: 'string' });
ajv.addKeyword({ keyword: 'x-sdd-error', schemaType: 'string' });
// $anchor (common.schema.json#ProblemDetails) es solo anotación: ningún $ref lo usa, todos usan punteros JSON.
ajv.addKeyword({ keyword: '$anchor', schemaType: 'string' });

for (const { doc } of schemas) ajv.addSchema(doc, doc.$id);

// Nombres de tipos y validadores: cada $defs y cada raíz con "type".
const typeRegistry = new Map(); // nombre -> { ref, file }
function registerType(name, ref, file) {
  if (typeRegistry.has(name)) {
    fail(`nombre de tipo duplicado "${name}" en ${file} y ${typeRegistry.get(name).file}`);
  }
  typeRegistry.set(name, { ref, file });
}
for (const { file, doc } of schemas) {
  if (doc.type) registerType(doc.title.replace(/Schema$/, ''), doc.$id, file);
  for (const name of Object.keys(doc.$defs ?? {}).sort()) {
    registerType(name, `${doc.$id}#/$defs/${name}`, file);
  }
}

const validatorRefs = {};
for (const [name, { ref }] of [...typeRegistry.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  validatorRefs[`validate${name}`] = ref;
}

let validatorsCode;
try {
  validatorsCode = standaloneCode(ajv, validatorRefs);
} catch (error) {
  fail(`Ajv no pudo generar los validadores: ${error.message}`);
}

const allTraceability = [...new Set(schemas.flatMap(({ doc }) => metaOf(doc).traceability ?? []))].sort();
const schemaSources = schemas.map(({ rel, doc }) => sourceLabel(rel, doc));

emit(
  'schemas/validators.cjs',
  `${banner({ sources: schemaSources, implementsIds: allTraceability })}\n${validatorsCode}`,
);

const typeNames = [...typeRegistry.keys()].sort();
emit(
  'schemas/validators.d.cts',
  [
    banner({ sources: schemaSources, implementsIds: allTraceability }),
    `import type { ErrorObject } from 'ajv';`,
    `import type { ${typeNames.join(', ')} } from './types';`,
    '',
    'export interface ValidatorFunction<T> {',
    '  (data: unknown): data is T;',
    '  errors?: ErrorObject[] | null;',
    '}',
    '',
    ...typeNames.map((n) => `export declare const validate${n}: ValidatorFunction<${n}>;`),
  ].join('\n'),
);

// ---------------------------------------------------------------------------
// 3. Tipos desde los esquemas (json-schema-to-typescript, un único paquete de tipos)
// ---------------------------------------------------------------------------
// Copia solo para tipos: la raíz con "type" toma el nombre del registro (PetProfileSchema -> PetProfile).
const schemaByUrl = new Map(
  schemas.map(({ doc }) => [doc.$id, doc.type ? { ...doc, title: doc.title.replace(/Schema$/, '') } : doc]),
);
const bundle = {
  $id: 'https://argos.local/contracts/bundle.generated.json',
  title: 'ArgosContractsIndex',
  type: 'object',
  additionalProperties: false,
  properties: {},
  $defs: Object.fromEntries([...typeRegistry.entries()].map(([name, { ref }]) => [name, { $ref: ref }])),
};

const typesBody = await compileTypes(bundle, 'ArgosContractsIndex', {
  bannerComment: '',
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  additionalProperties: false,
  cwd: contractsDir,
  $refOptions: {
    resolve: {
      http: false,
      file: false,
      argos: {
        order: 1,
        canRead: /^https:\/\/argos\.local\//,
        read: (file) => {
          const url = file.url.replace(/#.*$/, '');
          const doc = schemaByUrl.get(url);
          if (!doc) throw new Error(`esquema no registrado: ${url}`);
          return JSON.stringify(doc);
        },
      },
    },
  },
});

for (const name of typeNames) {
  const declared = new RegExp(`export (interface|type) ${name}\\b`).test(typesBody);
  if (!declared) fail(`json-schema-to-typescript no declaró el tipo "${name}"`);
}

emit(
  'schemas/types.ts',
  `${banner({ sources: schemaSources, implementsIds: allTraceability })}\n\n${typesBody
    .replace(/export interface ArgosContractsIndex \{\s*\}\s*/g, '')
    .trimEnd()}`,
);

// ---------------------------------------------------------------------------
// 4. Catálogo de errores y mapa campo -> código (x-sdd-error)
// ---------------------------------------------------------------------------
const errorCodes = Object.keys(errorEntries).sort();
const catalogMeta = metaOf(catalog);
const catalogSource = sourceLabel('contracts/errors/error-catalog.json', catalog);

const sortedEntries = Object.fromEntries(errorCodes.map((c) => [c, errorEntries[c]]));

emit(
  'errors/error-codes.ts',
  [
    banner({ sources: [catalogSource], implementsIds: [...(catalogMeta.traceability ?? [])] }),
    `import type { ProblemDetails } from '../schemas/types.ts';`,
    '',
    `export const ERROR_CATALOG = ${JSON.stringify(sortedEntries, null, 2)} as const;`,
    '',
    'export type ErrorCode = keyof typeof ERROR_CATALOG;',
    '',
    'export const ERROR_CODES = Object.keys(ERROR_CATALOG) as ErrorCode[];',
    '',
    `export type RollbackFinalState = 'ROLLED_BACK' | 'UNKNOWN';`,
    '',
    '/** Error determinista de dominio alineado con contracts/errors/error-catalog.json. */',
    'export class DomainError extends Error {',
    '  public readonly code: ErrorCode;',
    '  public readonly title: string;',
    '  public readonly status: number;',
    '  public readonly detail: string;',
    '  public readonly invariantRef: string;',
    '  public readonly field: string | null;',
    '  public readonly finalState: RollbackFinalState | null;',
    '',
    '  constructor(',
    '    code: ErrorCode,',
    '    customDetail?: string,',
    '    field: string | null = null,',
    '    finalState: RollbackFinalState | null = null,',
    '  ) {',
    '    const entry = ERROR_CATALOG[code];',
    '    const detail = customDetail ?? entry.detailTemplate;',
    '    super(`[${code}] ${detail}`);',
    `    this.name = 'DomainError';`,
    '    this.code = code;',
    '    this.title = entry.title;',
    '    this.status = entry.status;',
    '    this.detail = detail;',
    '    this.invariantRef = entry.invariantRef;',
    '    this.field = field;',
    '    this.finalState = finalState;',
    '  }',
    '',
    '  public toProblemDetails(instance: string | null = null): ProblemDetails {',
    '    return {',
    '      type: `urn:argos:error:${this.code}`,',
    '      code: this.code,',
    '      title: this.title,',
    '      status: this.status,',
    '      detail: this.detail,',
    '      invariantRef: this.invariantRef,',
    '      field: this.field,',
    '      instance,',
    '      ...(this.finalState === null ? {} : { finalState: this.finalState }),',
    '    };',
    '  }',
    '}',
  ].join('\n'),
);

/** Resuelve un $ref (local "#/..." o absoluto a otro esquema registrado) a { node, doc }. */
function followRef(ref, currentDoc) {
  const [base, pointer = ''] = ref.split('#');
  const targetDoc = base ? schemaByUrl.get(base) : currentDoc;
  if (!targetDoc) return undefined;
  let node = targetDoc;
  for (const part of pointer.split('/').slice(1)) {
    node = node?.[part.replace(/~1/g, '/').replace(/~0/g, '~')];
  }
  return node && typeof node === 'object' ? { node, doc: targetDoc } : undefined;
}

/** Código x-sdd-error de un nodo, directo o heredado por $ref / allOf. */
function annotationOf(node, doc, depth = 0) {
  if (!node || typeof node !== 'object' || depth > 8) return undefined;
  if (typeof node['x-sdd-error'] === 'string') return node['x-sdd-error'];
  if (typeof node.$ref === 'string') {
    const target = followRef(node.$ref, doc);
    const inherited = target ? annotationOf(target.node, target.doc, depth + 1) : undefined;
    if (inherited) return inherited;
  }
  for (const sub of node.allOf ?? []) {
    const inherited = annotationOf(sub, doc, depth + 1);
    if (inherited) return inherited;
  }
  return undefined;
}

/** Recorre un esquema y recoge { campo: código } de las anotaciones x-sdd-error. */
function collectFieldErrors(node, acc, doc) {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (const child of node) collectFieldErrors(child, acc, doc);
    return;
  }
  for (const [key, value] of Object.entries(node)) {
    if (key === 'properties' && value && typeof value === 'object') {
      for (const [field, sub] of Object.entries(value)) {
        const code = annotationOf(sub, doc);
        if (code !== undefined) {
          if (!(code in errorEntries)) fail(`x-sdd-error "${code}" en "${field}" no existe en el catálogo`);
          if (acc[field] && acc[field] !== code) fail(`campo "${field}" con códigos x-sdd-error distintos`);
          acc[field] = code;
        }
        collectFieldErrors(sub, acc, doc);
      }
    } else if (key !== 'x-sdd-metadata') {
      collectFieldErrors(value, acc, doc);
    }
  }
}

const fieldErrors = {};
for (const { doc } of schemas) {
  for (const defName of Object.keys(doc.$defs ?? {}).sort()) {
    const acc = {};
    collectFieldErrors(doc.$defs[defName], acc, doc);
    if (Object.keys(acc).length > 0) fieldErrors[defName] = Object.fromEntries(Object.entries(acc).sort());
  }
}

emit(
  'errors/field-errors.ts',
  [
    banner({ sources: schemaSources, implementsIds: allTraceability }),
    `import type { ErrorCode } from './error-codes.ts';`,
    '',
    '/** Mapa esquema -> campo -> código de error, derivado de x-sdd-error. */',
    `export const FIELD_ERROR_CODES: Readonly<Record<string, Readonly<Record<string, ErrorCode>>>> = ${JSON.stringify(fieldErrors, null, 2)};`,
    '',
    '/** Devuelve el código de error del campo al que apunta instancePath de Ajv, si el contrato define uno. */',
    'export function resolveFieldErrorCode(schemaName: string, instancePath: string): ErrorCode | undefined {',
    '  const fields = FIELD_ERROR_CODES[schemaName];',
    '  if (fields === undefined) return undefined;',
    `  const segments = instancePath.split('/').filter((s) => s !== '' && !/^\\d+$/.test(s));`,
    '  const field = segments[segments.length - 1];',
    '  return field === undefined ? undefined : fields[field];',
    '}',
  ].join('\n'),
);

// ---------------------------------------------------------------------------
// 5. Máquinas de estado: cada una se lee de su propio archivo
// ---------------------------------------------------------------------------
for (const { file, rel, doc } of machineDocs) {
  const ids = Object.keys(doc.machines ?? {});
  if (ids.length === 0) fail(`${file} no declara machines`);
  const parts = [];
  for (const id of ids) {
    if (doc.id && doc.id !== id && ids.length === 1) fail(`${file}: id "${doc.id}" no coincide con la máquina "${id}"`);
    const machine = doc.machines[id];
    if (!machine.states) fail(`${file}: la máquina ${id} no tiene states`);
    const constName = screamingSnake(id);
    const typeBase = pascal(id);
    const stateNames = Object.keys(machine.states);
    parts.push(`export const ${constName} = ${JSON.stringify(machine, null, 2)} as const;`);
    parts.push(
      `export const ${constName}_STATES = ${JSON.stringify(stateNames)} as const;`,
      `export type ${typeBase}State = (typeof ${constName}_STATES)[number];`,
    );
    const events = [
      ...new Set(
        stateNames.flatMap((s) => Object.keys(machine.states[s]?.on ?? {})),
      ),
    ].sort();
    if (events.length > 0) {
      parts.push(
        `export const ${constName}_EVENTS = ${JSON.stringify(events)} as const;`,
        `export type ${typeBase}Event = (typeof ${constName}_EVENTS)[number];`,
      );
    }
  }
  const meta = metaOf(doc);
  emit(
    `machines/${basename(file, '.machine.json')}.machine.ts`,
    [
      banner({ sources: [sourceLabel(rel, doc)], implementsIds: [...(meta.traceability ?? [])] }),
      '',
      parts.join('\n\n'),
    ].join('\n'),
  );
}

// ---------------------------------------------------------------------------
// 6. OpenAPI: tipos (openapi-typescript) y cliente (openapi-fetch)
// ---------------------------------------------------------------------------
// openapi-typescript no resuelve los $ref con URL absoluta (https://argos.local/...): intentaría descargarlos.
// Se usa una copia temporal donde esos $ref pasan a ser relativos; contracts/ no se modifica.
const openapiWorkDir = mkdtempSync(join(tmpdir(), 'argos-openapi-'));
let openapiTypes;
try {
  mkdirSync(join(openapiWorkDir, 'schemas'), { recursive: true });
  cpSync(openapiDir, join(openapiWorkDir, 'openapi'), { recursive: true });
  for (const { file, doc } of schemas) {
    const text = JSON.stringify(doc).replace(
      /("\$ref":")https:\/\/argos\.local\/contracts\/schemas\//g,
      '$1./',
    );
    writeFileSync(join(openapiWorkDir, 'schemas', file), text, 'utf8');
  }
  const openapiAst = await openapiTS(pathToFileURL(join(openapiWorkDir, 'openapi', openapiFile)));
  openapiTypes = astToString(openapiAst);
} finally {
  rmSync(openapiWorkDir, { recursive: true, force: true });
}
const openapiMeta = metaOf(openapiDoc.info ?? {});
const openapiSource = `contracts/openapi/${openapiFile} (v${openapiMeta.version}, ${openapiMeta.status})`;

emit(
  'api/openapi-types.ts',
  `${banner({ sources: [openapiSource], implementsIds: [...(openapiMeta.traceability ?? [])] })}\n\n${openapiTypes.trimEnd()}`,
);

const csrfParam = openapiDoc.components?.parameters?.CsrfHeader;
if (!csrfParam || csrfParam.in !== 'header' || csrfParam.schema?.const === undefined) {
  fail('OpenAPI sin components.parameters.CsrfHeader con valor const');
}

emit(
  'api/client.ts',
  [
    banner({ sources: [openapiSource], implementsIds: ['INV-AUTH-007'] }),
    `import createClient from 'openapi-fetch';`,
    `import type { paths } from './openapi-types.ts';`,
    '',
    `export const CSRF_HEADER_NAME = ${JSON.stringify(csrfParam.name)};`,
    `export const CSRF_HEADER_VALUE = ${JSON.stringify(String(csrfParam.schema.const))};`,
    '',
    '/** Cliente HTTP tipado desde el OpenAPI; añade la cabecera CSRF obligatoria [INV-AUTH-007]. */',
    `export function createApiClient(baseUrl = '/api') {`,
    '  return createClient<paths>({',
    '    baseUrl,',
    '    headers: { [CSRF_HEADER_NAME]: CSRF_HEADER_VALUE },',
    '  });',
    '}',
  ].join('\n'),
);

// ---------------------------------------------------------------------------
// 7. Índice
// ---------------------------------------------------------------------------
emit(
  'index.ts',
  [
    banner({ sources: ['contracts/**'], implementsIds: [] }),
    `export * from './errors/error-codes.ts';`,
    `export * from './errors/field-errors.ts';`,
    `export type * from './schemas/types.ts';`,
    `export * from './schemas/validators.cjs';`,
    ...machineDocs.map(({ file }) => `export * from './machines/${basename(file, '.machine.json')}.machine.ts';`),
    `export * from './api/client.ts';`,
    `export type { paths, components, operations } from './api/openapi-types.ts';`,
  ].join('\n'),
);

// ---------------------------------------------------------------------------
// 8. Verificaciones previas a escribir y escritura determinista
// ---------------------------------------------------------------------------
for (const [relPath, content] of emitted) {
  for (const retired of RETIRED_IDS) {
    if (content.includes(retired)) fail(`la salida ${relPath} contiene el ID retirado ${retired}`);
  }
}

if (existsSync(outDir)) {
  for (const entry of readdirSync(outDir)) {
    if (entry === '.gitkeep') continue;
    rmSync(join(outDir, entry), { recursive: true, force: true });
  }
}
mkdirSync(outDir, { recursive: true });

for (const relPath of [...emitted.keys()].sort()) {
  const target = join(outDir, relPath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, emitted.get(relPath), 'utf8');
}

console.log('[codegen] Contratos leídos:');
for (const { rel, doc } of [...schemas, ...machineDocs]) {
  const meta = metaOf(doc);
  console.log(`  ${rel}  v${meta.version}  ${meta.status}`);
}
console.log(`  contracts/errors/error-catalog.json  v${catalogMeta.version}  ${catalogMeta.status}`);
console.log(`  contracts/openapi/${openapiFile}  v${openapiMeta.version}  ${openapiMeta.status}`);
console.log(`[codegen] Validadores: ${Object.keys(validatorRefs).length}; errores: ${errorCodes.length}; máquinas: ${machineDocs.length}`);
console.log(`[codegen] Archivos generados en ${outDir}:`);
for (const relPath of [...emitted.keys()].sort()) {
  console.log(`  ${relPath} (${emitted.get(relPath).split('\n').length - 1} líneas)`);
}
